// Rebuilds the web app in ../workout-app and embeds it for the native shell: node scripts/sync-web.js
// The shell loads the page from this string, so the app works with no network at all.
const fs = require('fs'), path = require('path'), { execFileSync } = require('child_process');
const web = path.join(__dirname, '..', '..', 'workout-app');
execFileSync('node', ['build.js'], { cwd: web, stdio: 'inherit' });
// the page, with the font built in (scripts/page.js)
const page = require('./page').writePage(web);
// the coach: the Anthropic SDK and web/coach.js as one script the shell puts next to the page
const coach = require('esbuild').buildSync({ entryPoints: [path.join(__dirname, '..', 'web', 'coach.js')], bundle: true, minify: true, format: 'iife', platform: 'browser', target: ['safari15', 'chrome100'], write: false, legalComments: 'none' }).outputFiles[0].text;
fs.writeFileSync(path.join(__dirname, '..', 'src', 'coachBundle.js'), '// Generated by scripts/sync-web.js from web/coach.js and @anthropic-ai/sdk. Do not edit by hand.\nexport default ' + JSON.stringify(coach) + ';\n');
console.log('wrote src/coachBundle.js', (coach.length / 1024).toFixed(1) + ' KB');
console.log('wrote src/gymiPage.js', (page.length / 1024).toFixed(1) + ' KB');
