// The page as the phone app embeds it: ../workout-app/index.html, with the Rubik font inside it instead of a link to
// Google Fonts. The app then starts with no network at all, sends nothing to Google, and a slow network cannot hold up
// its first screen. Rubik is under the SIL Open Font License (assets/fonts/OFL.txt). The web version keeps the link.
const fs = require('fs'), path = require('path');

const LINK = /<link rel="stylesheet" href="https:\/\/fonts\.googleapis\.com\/[^"]*">\n?/;
const FONT = path.join(__dirname, '..', 'assets', 'fonts', 'Rubik-wght.ttf');

function phonePage(page) {
  if (!LINK.test(page)) throw new Error('the page no longer links Rubik from Google Fonts: update scripts/page.js');
  const font = fs.readFileSync(FONT).toString('base64');
  /* one variable font for every weight the page uses (400 to 800) */
  return page.replace(LINK, () => '<style>@font-face{font-family:"Rubik";font-style:normal;font-weight:300 900;font-display:swap;src:url(data:font/ttf;base64,' + font + ') format("truetype")}</style>\n');
}

/* writes src/gymiPage.js from an index.html that is already built */
function writePage(web) {
  const page = phonePage(fs.readFileSync(path.join(web, 'index.html'), 'utf8'));
  fs.writeFileSync(path.join(__dirname, '..', 'src', 'gymiPage.js'), '// Generated by scripts/sync-web.js from ../workout-app. Do not edit by hand.\nexport default ' + JSON.stringify(page) + ';\n');
  return page;
}

module.exports = { phonePage, writePage };
